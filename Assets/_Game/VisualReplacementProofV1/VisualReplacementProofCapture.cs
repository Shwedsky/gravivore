        private void AimCamera(Vector3 target)
        {
            _reviewCamera.transform.position = target + MandatoryCameraOffset;
            _reviewCamera.transform.rotation = Quaternion.LookRotation(target - _reviewCamera.transform.position, Vector3.up);
            _reviewCamera.fieldOfView = CameraFov;
        }

        private string ResolveOutputDirectory()
        {
            var projectRoot = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
            return Path.GetFullPath(Path.Combine(projectRoot, outputDirectory));
        }

        private GameObject NewRoot(string name)
        {
            var go = new GameObject(name);
            go.transform.SetParent(transform, false);
            return go;
        }

        private static Transform NewSocket(Transform parent, string name, Vector3 localPosition)
        {
            var socket = new GameObject(name).transform;
            socket.SetParent(parent, false);
            socket.localPosition = localPosition;
            socket.localRotation = Quaternion.identity;
            return socket;
        }

        private void AddLoft(Transform parent, string name, IReadOnlyList<VisualProofMeshFactory.LoftRing> rings, int sides, Vector3 localPosition, Quaternion localRotation, string material)
        {
            AddMesh(parent, name, VisualProofMeshFactory.CreateLoft("VRP1_" + name, rings, sides), localPosition, localRotation, material);
        }

        private void AddExtruded(Transform parent, string name, IReadOnlyList<Vector2> polygon, float depth, Vector3 localPosition, Quaternion localRotation, string material)
        {
            AddMesh(parent, name, VisualProofMeshFactory.CreateExtrudedPolygon("VRP1_" + name, polygon, depth), localPosition, localRotation, material);
        }

        private void AddTube(Transform parent, string name, IReadOnlyList<Vector3> points, float radius, int sides, string material)
        {
            AddMesh(parent, name, VisualProofMeshFactory.CreateTube("VRP1_" + name, points, radius, sides), Vector3.zero, Quaternion.identity, material);
        }

        private void AddTorus(Transform parent, string name, float majorRadius, float minorRadius, int majorSegments, int minorSegments, Vector3 localPosition, Quaternion localRotation, string material)
        {
            AddMesh(parent, name, VisualProofMeshFactory.CreateTorus("VRP1_" + name, majorRadius, minorRadius, majorSegments, minorSegments), localPosition, localRotation, material);
        }

        private void AddMesh(Transform parent, string name, Mesh mesh, Vector3 localPosition, Quaternion localRotation, string material)
        {
            var go = new GameObject(name);
            go.transform.SetParent(parent, false);
            go.transform.localPosition = localPosition;
            go.transform.localRotation = localRotation;
            var filter = go.AddComponent<MeshFilter>();
            filter.sharedMesh = mesh;
            var renderer = go.AddComponent<MeshRenderer>();
            renderer.sharedMaterial = _materials[material];
            renderer.shadowCastingMode = ShadowCastingMode.On;
            renderer.receiveShadows = true;
        }

        private static VisualProofMeshFactory.LoftRing Ring(float y, float x, float z, float offsetX = 0f, float offsetZ = 0f, float rotationDegrees = 0f)
        {
            return new VisualProofMeshFactory.LoftRing(y, x, z, offsetX, offsetZ, rotationDegrees);
        }

        private static Vector2[] ChamferedPolygon(float width, float height, float chamfer)
        {
            var x = width * 0.5f;
            var y = height * 0.5f;
            var c = Mathf.Clamp(chamfer, 0.001f, Mathf.Min(x, y) * 0.45f);
            return new[] { new Vector2(-x + c, -y), new Vector2(x - c, -y), new Vector2(x, -y + c), new Vector2(x, y - c), new Vector2(x - c, y), new Vector2(-x + c, y), new Vector2(-x, y - c), new Vector2(-x, -y + c) };
        }

        private static Vector2[] BladePolygon(float length, float height)
        {
            return new[] { new Vector2(-length * 0.5f, -height * 0.5f), new Vector2(length * 0.30f, -height * 0.34f), new Vector2(length * 0.5f, 0f), new Vector2(length * 0.30f, height * 0.34f), new Vector2(-length * 0.5f, height * 0.5f) };
        }

        private static string SideName(float side, string suffix) => (side < 0f ? "Left_" : "Right_") + suffix;
