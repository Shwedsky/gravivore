            _deathProxyRoot.gameObject.SetActive(deathProxy);

            if (focus != null)
            {
                focus.gameObject.SetActive(true);
            }

            AimCamera(target);
            yield return null;
            RenderFrame(Path.Combine(ResolveOutputDirectory(), fileName));
        }

        private void RenderFrame(string path)
        {
            const int width = 1080;
            const int height = 1920;

            var renderTexture = new RenderTexture(width, height, 24, RenderTextureFormat.ARGB32)
            {
                name = "VRP1_ReviewCapture",
                antiAliasing = 1
            };

            var previousTarget = _reviewCamera.targetTexture;
            var previousActive = RenderTexture.active;

            try
            {
                _reviewCamera.targetTexture = renderTexture;
                RenderTexture.active = renderTexture;
                _reviewCamera.Render();

                var texture = new Texture2D(width, height, TextureFormat.RGB24, false, false);
                texture.ReadPixels(new Rect(0f, 0f, width, height), 0, 0, false);
                texture.Apply(false, false);
                File.WriteAllBytes(path, texture.EncodeToPNG());
                Destroy(texture);
            }
            finally
            {
                _reviewCamera.targetTexture = previousTarget;
                RenderTexture.active = previousActive;
                renderTexture.Release();
                Destroy(renderTexture);
            }
        }

        private void WriteMetrics(string path)
        {
            var lines = new List<string>
            {
                "# Visual Replacement Proof V1 — measured runtime metrics",
                "",
                "Generated by the isolated proof scene from the actual constructed meshes.",
                "",
                "| Actor | Triangles | Renderers | Material slots | Unique materials | Texture sizes | Mesh mode | Animation clips |",
                "|---|---:|---:|---:|---:|---|---|---:|"
            };

            lines.Add(MetricRow("G-0", _g0Root));
            lines.Add(MetricRow("Scout", _scoutRoot));
            lines.Add(MetricRow("Cutter", _cutterRoot));
            lines.Add("");
            lines.Add("Surface variation is generated deterministically at runtime (128–256 px) for selected armor/metal/floor materials. There are **0 imported texture bytes** and no third-party texture license dependency.");
            lines.Add("All actor renderers are static MeshRenderer/MeshFilter renderers; V1 contains no SkinnedMeshRenderer and no animation clips.");
            lines.Add("The proof intentionally measures presentation geometry only. It is not wired into Chapter01 or gameplay.");

            File.WriteAllLines(path, lines);
        }

        private string MetricRow(string label, Transform root)
        {
            var filters = root.GetComponentsInChildren<MeshFilter>(true);
            var renderers = root.GetComponentsInChildren<Renderer>(true);
            long triangleCount = 0;

            foreach (var filter in filters)
            {
                var mesh = filter.sharedMesh;
                if (mesh != null)
                {
                    triangleCount += mesh.triangles.LongLength / 3L;
                }
            }

            var materialSlots = renderers.Sum(r => r.sharedMaterials != null ? r.sharedMaterials.Length : 0);
            var actorMaterials = renderers
                .SelectMany(r => r.sharedMaterials ?? Array.Empty<Material>())
                .Where(m => m != null)
                .Distinct()
                .ToArray();
            var uniqueMaterialCount = actorMaterials.Length;
            var textureSizes = actorMaterials
                .Select(m => m.GetTexture("_BaseMap") as Texture2D)
                .Where(t => t != null && t.name.StartsWith("VRP1_", StringComparison.Ordinal))
                .Select(t => t.width + "x" + t.height)
                .Distinct(StringComparer.Ordinal)
                .OrderBy(v => v, StringComparer.Ordinal)
                .ToArray();
            var textureSummary = textureSizes.Length == 0 ? "none" : string.Join(", ", textureSizes);

            return $"| {label} | {triangleCount} | {renderers.Length} | {materialSlots} | {uniqueMaterialCount} | {textureSummary} procedural | static MeshFilter | 0 |";
        }

        private void SetActorVisibility(bool g0, bool scout, bool cutter)
        {
            _g0Root.gameObject.SetActive(g0);
            _scoutRoot.gameObject.SetActive(scout);
            _cutterRoot.gameObject.SetActive(cutter);
